"""`runspace init <tenant-id>` — scaffold a new tenant."""

from __future__ import annotations

import sys
from pathlib import Path
from textwrap import dedent


def run_init(
    *,
    tenant_id: str,
    target_dir: Path,
    name: str | None = None,
    icon: str = "🗂",
    brand_color: str = "#3B82F6",
    interactive: bool = True,
) -> int:
    """Scaffold tenants/<tenant_id>/ under target_dir."""

    if not _valid_tenant_id(tenant_id):
        print(
            f"ERROR: tenant_id {tenant_id!r} must be lowercase letters/digits/-, "
            f"start with a letter, length 1–32",
            file=sys.stderr,
        )
        return 2

    tenant_dir = target_dir / "tenants" / tenant_id
    if tenant_dir.exists():
        print(f"ERROR: {tenant_dir} already exists — refusing to overwrite", file=sys.stderr)
        return 3

    # Every prompt already shows the value it will use, so a closed stdin —
    # CI, a Dockerfile, `runspace init x < /dev/null` — takes the default
    # rather than crashing with an unhandled EOFError half-scaffolded.
    def ask(prompt: str) -> str:
        try:
            return input(prompt).strip()
        except EOFError:
            print("(no input available — using the default)", file=sys.stderr)
            return ""

    if interactive and not name:
        name = ask(f"Display name for {tenant_id} [{tenant_id.replace('-', ' ').title()}]: ")
    name = name or tenant_id.replace("-", " ").title()

    if interactive:
        ans = ask(f"Brand color [{brand_color}]: ")
        if ans:
            brand_color = ans
        ans = ask(f"Workspace icon (emoji) [{icon}]: ")
        if ans:
            icon = ans

    tenant_dir.mkdir(parents=True)
    (tenant_dir / "agents").mkdir()
    (tenant_dir / "plugins").mkdir()

    _write(tenant_dir / "workspace.yml", _workspace_yml(tenant_id, name, icon, brand_color))
    _write(tenant_dir / "config.yaml", _config_yaml())
    _write(tenant_dir / "routines.yml", _routines_yml())
    _write(tenant_dir / "plugins" / "__init__.py", "")
    _write(tenant_dir / "plugins" / "health.py", _example_plugin_health())
    _write(tenant_dir / ".npmrc", _npmrc())
    _write(tenant_dir / "Dockerfile", _dockerfile(tenant_id))
    _write(tenant_dir / "docker-compose.yml", _docker_compose(tenant_id))
    _write(tenant_dir / "README.md", _readme(tenant_id, name))

    print(f"\n✅ tenant scaffolded at {tenant_dir}\n")
    print("Next steps:")
    print(f"  cd {tenant_dir}")
    print("  # Add your agents under agents/<role>/SOUL.md + tools/")
    print("  # Edit workspace.yml plugins: list as you add plugin modules")
    print("  python -m runspace.workspace.serve workspace.yml   # local boot")
    print("  docker compose up                                    # docker boot")
    return 0


